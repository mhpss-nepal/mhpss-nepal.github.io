/* =====================================================================
   MHPSS Nepal -- the GBV & CP referral pathway on the Referral Directory
   ---------------------------------------------------------------------
   Draws window.REFERRAL_PATHWAY (assets/referral-pathway.js, generated by
   tools/pathway-build.py) as cards grouped by district, with four filters.
   The districts of the flood response come first and open; the rest are
   folded. Organisations and services only -- the data file carries no
   person, number, email or address, and a shelter has no place below its
   district, so nothing here can show one.

   When the reader picks a district in "Find a service" above, the same
   district is picked here, so one choice answers both lists.
   ===================================================================== */
(function () {
  "use strict";
  var P = window.REFERRAL_PATHWAY;
  var res = document.getElementById("pwRes");
  if (!P || !res) return;

  var FLOOD = ["Rasuwa", "Nuwakot", "Dhading", "Gorkha", "Tanahun"];
  var PROV = ["Koshi", "Madhesh", "Bagmati", "Gandaki", "Lumbini", "Karnali", "Sudur Pashchim"];
  var WHO = ["women", "men", "girls", "boys", "older", "lgbtqi"];
  var $ = function (id) { return document.getElementById(id); };
  function t(k, v) { return window.I18N ? window.I18N.t(k, v) : k; }
  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }
  function monthName(ym) {
    if (!/^\d{4}-\d{2}$/.test(ym || "")) return "";
    var d = new Date(ym + "-01T00:00:00Z");
    return d.toLocaleDateString("en-GB", { month: "long", year: "numeric", timeZone: "UTC" }).replace(/ /g, " ");
  }
  function distOf(r) { return r.dist || t("pw.nodist"); }

  var rows = P.rows || [];
  var state = { prov: "", dist: "", cat: "", mh: "" };

  function fill(sel, allKey, values, cur) {
    var keep = sel.value;
    sel.innerHTML = "";
    var o = el("option", null, t(allKey)); o.value = ""; sel.appendChild(o);
    values.forEach(function (v) { var x = el("option", null, v[1]); x.value = v[0]; sel.appendChild(x); });
    sel.value = cur != null ? cur : keep;
    if (sel.value !== (cur != null ? cur : keep)) sel.value = "";
  }

  function pass(r, skip) {
    if (skip !== "prov" && state.prov && r.prov !== state.prov) return false;
    if (skip !== "dist" && state.dist && r.dist !== state.dist) return false;
    if (skip !== "cat" && state.cat && r.cat !== state.cat) return false;
    if (skip !== "mh" && state.mh && r.mh !== state.mh) return false;
    return true;
  }

  function filters() {
    var provs = PROV.filter(function (p) { return rows.some(function (r) { return r.prov === p && pass(r, "prov"); }); });
    fill($("pwProv"), "pw.all.prov", provs.map(function (p) { return [p, p]; }), state.prov);
    var dists = {};
    rows.forEach(function (r) { if (r.dist && pass(r, "dist")) dists[r.dist] = 1; });
    var dl = Object.keys(dists).sort(function (a, b) {
      var fa = FLOOD.indexOf(a), fb = FLOOD.indexOf(b);
      if (fa >= 0 || fb >= 0) return (fa < 0 ? 99 : fa) - (fb < 0 ? 99 : fb);
      return a.localeCompare(b);
    });
    fill($("pwDist"), "pw.all.dist", dl.map(function (d) { return [d, d]; }), state.dist);
    var cats = {};
    rows.forEach(function (r) { if (pass(r, "cat")) cats[r.cat] = 1; });
    fill($("pwCat"), "pw.all.cat", Object.keys(cats).sort().map(function (c) { return [c, c]; }), state.cat);
    fill($("pwMh"), "pw.all.mh", [["core", t("pw.mh.core")], ["component", t("pw.mh.component")]], state.mh);
  }

  function card(r) {
    var li = el("li", "fcard pwcard");
    var h = el("div", "fc-h"); h.appendChild(el("b", null, r.org)); li.appendChild(h);
    var place = r.shelter ? t("pw.shelterPlace", { dist: distOf(r) })
                          : (r.pal ? r.pal + " · " + distOf(r) : distOf(r) + " · " + t("pw.nopal"));
    li.appendChild(el("p", "fc-place", place));
    var tags = el("div", "pwtags");
    tags.appendChild(el("span", "tagpill", r.cat));
    tags.appendChild(el("span", "tagpill " + (r.mh === "core" ? "core" : "comp"), t("pw.mh." + r.mh)));
    if (r.spec) tags.appendChild(el("span", "tagpill spec", t("pw.spec")));
    li.appendChild(tags);
    if (r.det) li.appendChild(el("p", "fc-meta pwdet", "“" + r.det + "”"));
    var meta = [];
    if (r.pt) meta.push([t("pw.k.pt"), r.pt]);
    if (r.hrs) meta.push([t("pw.k.hrs"), r.hrs]);
    if (r.lang) meta.push([t("pw.k.lang"), r.lang]);
    if (r.acc) meta.push([t("pw.k.acc"), r.acc]);
    if (r.who && r.who.length) meta.push([t("pw.k.who"), r.who.map(function (w) { return t("pw.who." + w); }).join(", ")]);
    if (r.upd) meta.push([t("pw.k.upd"), monthName(r.upd)]);
    meta.forEach(function (m) {
      var p = el("p", "fc-meta");
      p.appendChild(el("span", "how", m[0] + ": "));
      p.appendChild(document.createTextNode(m[1]));
      li.appendChild(p);
    });
    return li;
  }

  function render() {
    filters();
    var shown = rows.filter(function (r) { return pass(r); });
    var by = {};
    shown.forEach(function (r) { (by[distOf(r)] = by[distOf(r)] || []).push(r); });
    var dists = Object.keys(by).sort(function (a, b) {
      var fa = FLOOD.indexOf(a), fb = FLOOD.indexOf(b);
      if (fa >= 0 || fb >= 0) return (fa < 0 ? 99 : fa) - (fb < 0 ? 99 : fb);
      return a.localeCompare(b);
    });
    $("pwSum").textContent = t(shown.length === 1 ? "pw.sum.one" : (dists.length === 1 ? "pw.sum.d1" : "pw.sum"), { n: shown.length, d: dists.length });
    res.innerHTML = "";
    /* the flood districts with nothing on the pathway are said, not hidden */
    if (!state.dist && !state.cat && !state.mh && (!state.prov || state.prov === "Bagmati" || state.prov === "Gandaki")) {
      var none = FLOOD.filter(function (d) { return !by[d]; });
      if (none.length) res.appendChild(el("p", "fnot", t("pw.floodNone", { names: none.join(", ") })));
    }
    dists.forEach(function (d) {
      var det = el("details", "pwd");
      if (FLOOD.indexOf(d) >= 0 || state.dist || dists.length <= 3) det.open = true;
      var s = el("summary");
      s.appendChild(el("b", null, d));
      s.appendChild(el("span", "n", String(by[d].length)));
      det.appendChild(s);
      var ul = el("ul", "fcards");
      by[d].forEach(function (r) { ul.appendChild(card(r)); });
      det.appendChild(ul);
      res.appendChild(det);
    });
  }

  ["Prov", "Dist", "Cat", "Mh"].forEach(function (k) {
    $("pw" + k).addEventListener("change", function (e) {
      state[k.toLowerCase()] = e.target.value;
      if (k === "Prov") state.dist = "";
      render();
    });
  });
  $("pwClear").addEventListener("click", function () { state = { prov: "", dist: "", cat: "", mh: "" }; render(); });

  /* one choice answers both lists: a district picked in "Find a service" */
  var fd = $("fDist");
  if (fd) fd.addEventListener("change", function () {
    var name = fd.selectedIndex > 0 ? fd.options[fd.selectedIndex].textContent.trim() : "";
    var hit = rows.some(function (r) { return r.dist === name; });
    state.dist = hit ? name : "";
    if (hit) state.prov = "";
    render();
  });

  render();
  document.addEventListener("i18n:changed", render);
})();
